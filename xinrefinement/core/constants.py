#: （D=inf）、Rwp 12.190 % —— 只差 0.85 %，按 Rwp 会选边界解，把 130 nm
#: 的样品报成"超出检出上限"。
#:
#: 规则：内部解 Rwp ≤ 边界解 Rwp × (1 + `TCH_BOUNDARY_TIE_TOL`) 时**取内部解**
#: —— 「拟合同样好时优先非边界解」是优化与 Rietveld 的通行做法，边界解
#: 本就先验可信度更低。容差 5 % 与 Rwp 的实验重现性同量级。
