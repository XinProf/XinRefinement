#: **边界解让位**判据（T8.2）。
#:
#: 双候选择优（`pipeline._pick_candidate`）按加权 Rwp 取优；但当**胜出者
#: 的 Y 停在下界 0**（= 无尺寸展宽，报告为"超出检出上限"）而另一候选是
#: **内部解**时，两者的 Rwp 差可能小于噪声，此时按 Rwp 选边界解是错的。
#:
