#: 收敛后 Y = 0.0507，对应 D = 155 nm）。
#:
#: 曾尝试把 LM 的雅可比改成"边界感知单边差分"，但那会改变 LM 的梯度
#: 尺度，进而改变非凸问题上的收敛路径，把已锚定的 T2.3 行为带偏
#: （"尺寸+应变"配置 Rwp 3.2058 → 3.8941）。**改初值比改优化器安全**。
